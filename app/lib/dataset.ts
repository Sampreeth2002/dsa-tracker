// ── Cadence scheduler ────────────────────────────────────────────────────
// Remaining work (hard sets + not-yet-done phases) is scheduled in this order,
// starting PLAN_START, at WEEKDAY_CAP problems on weekdays / WEEKEND_CAP on
// weekends (lighter days leave room for revision + system design practice).
